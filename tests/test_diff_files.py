"""Diff parser: kinds of file changes (new, deleted, renamed, ignored, odd paths)."""
from reviewer.diff import parse_diff


def test_new_file_is_added_with_every_line_commentable():
    diff = """\
diff --git a/app/new.py b/app/new.py
new file mode 100644
index 0000000..3333333
--- /dev/null
+++ b/app/new.py
@@ -0,0 +1,3 @@
+import os
+
+print(os.name)
"""
    [f] = parse_diff(diff)
    assert (f.path, f.change_type, f.old_path) == ("app/new.py", "added", None)
    assert f.added_lines == [1, 2, 3]
    assert f.commentable_lines == [1, 2, 3]
    assert f.deleted_positions == []


def test_deleted_file_has_no_new_side_lines():
    diff = """\
diff --git a/app/old.py b/app/old.py
deleted file mode 100644
index 3333333..0000000
--- a/app/old.py
+++ /dev/null
@@ -1,2 +0,0 @@
-import os
-print(os.name)
"""
    [f] = parse_diff(diff)
    assert (f.path, f.change_type) == ("app/old.py", "deleted")
    assert f.added_lines == [] and f.commentable_lines == [] and f.deleted_positions == []


def test_rename_with_edit_uses_the_new_path():
    diff = """\
diff --git a/app/a.py b/app/b.py
similarity index 80%
rename from app/a.py
rename to app/b.py
index 1111111..2222222 100644
--- a/app/a.py
+++ b/app/b.py
@@ -1,2 +1,3 @@
 x = 1
+y = 2
 z = 3
"""
    [f] = parse_diff(diff)
    assert (f.path, f.old_path, f.change_type) == ("app/b.py", "app/a.py", "renamed")
    assert f.added_lines == [2]


def test_pure_rename_has_no_hunks():
    diff = """\
diff --git a/app/a.py b/app/b.py
similarity index 100%
rename from app/a.py
rename to app/b.py
"""
    [f] = parse_diff(diff)
    assert (f.path, f.old_path, f.change_type) == ("app/b.py", "app/a.py", "renamed")
    assert f.hunks == [] and f.added_lines == [] and f.commentable_lines == []


def test_paths_with_spaces_are_kept_intact():
    diff = """\
diff --git a/my app/x y.py b/my app/x y.py
--- a/my app/x y.py\t
+++ b/my app/x y.py\t
@@ -1 +1,2 @@
 a = 1
+b = 2
"""
    [f] = parse_diff(diff)
    assert f.path == "my app/x y.py"
    assert f.added_lines == [2]


def test_lock_binary_and_generated_files_are_ignored():
    diff = """\
diff --git a/uv.lock b/uv.lock
--- a/uv.lock
+++ b/uv.lock
@@ -1 +1,2 @@
 a
+b
diff --git a/web/package-lock.json b/web/package-lock.json
--- a/web/package-lock.json
+++ b/web/package-lock.json
@@ -1 +1,2 @@
 a
+b
diff --git a/logo.png b/logo.png
index 1111111..2222222 100644
Binary files a/logo.png and b/logo.png differ
diff --git a/app/schema_pb2.py b/app/schema_pb2.py
--- a/app/schema_pb2.py
+++ b/app/schema_pb2.py
@@ -1,3 +1,4 @@
 # @generated by the protocol buffer compiler
 a = 1
+b = 2
 c = 3
diff --git a/app/real.py b/app/real.py
--- a/app/real.py
+++ b/app/real.py
@@ -1 +1,2 @@
 a = 1
+b = 2
"""
    assert [f.path for f in parse_diff(diff)] == ["app/real.py"]


def test_non_python_files_are_parsed_like_any_other():
    diff = """\
diff --git a/config.yaml b/config.yaml
--- a/config.yaml
+++ b/config.yaml
@@ -1,2 +1,3 @@
 a: 1
+b: 2
 c: 3
"""
    [f] = parse_diff(diff)
    assert f.path == "config.yaml" and f.added_lines == [2]


def test_hunk_header_without_counts_and_no_newline_marker():
    diff = """\
diff --git a/app/x.py b/app/x.py
--- a/app/x.py
+++ b/app/x.py
@@ -1 +1 @@
-a = 1
\\ No newline at end of file
+a = 2
\\ No newline at end of file
"""
    [f] = parse_diff(diff)
    assert f.added_lines == [1] and f.deleted_positions == [1]


def test_multiple_files_in_one_diff_and_empty_diff():
    diff = """\
diff --git a/a.py b/a.py
--- a/a.py
+++ b/a.py
@@ -1 +1,2 @@
 a = 1
+b = 2
diff --git a/b.py b/b.py
--- a/b.py
+++ b/b.py
@@ -3,2 +3,3 @@
 c = 3
+d = 4
 e = 5
"""
    files = parse_diff(diff)
    assert [(f.path, f.added_lines) for f in files] == [("a.py", [2]), ("b.py", [4])]
    assert parse_diff("") == []
